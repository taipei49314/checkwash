"""Generate benchmarks/FAILURES.md — every way this tool is known to be wrong.

    python benchmarks/make_failures.py

The material is already public: 80-odd rows in THREATMODEL.md, the adjudicated
false positives in the corpus, the agent escapes recorded in the decoy arms,
and the false positives this project shipped and had to correct. It is public
in four places and four formats, which is a fair distance from legible. This
collects it into one page, and generates it so the page cannot drift from the
files it summarises — the same reason RESULTS.md is generated, and the same
reason that mattered when RESULTS.md drifted anyway because a paragraph in the
generator was hardcoded.

Nothing here is hand-typed. If a row is missing from this document it is
missing from THREATMODEL.md.
"""

from __future__ import annotations

import json
import os
import re

# Split on unescaped pipes only. A row describing a shell `||` writes it
# as `\|\|` so the table renders, and splitting on raw "|" shifted every
# cell after it — the status column landed somewhere else and the row read
# as not-closed. Rows about shell operators are exactly the rows this
# ledger most needs to parse (found 2026-08-12).
_ROW_CELLS = re.compile(r"(?<!\\)\|")

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ADJUDICATION = "adjudication-2026-08-25.json"


def _load(*parts: str) -> dict:
    with open(os.path.join(*parts), encoding="utf-8") as fh:
        return json.load(fh)


def bypass_rows() -> list[tuple[str, str, str]]:
    """(number, shape, status) for every row in the bypass tables."""
    text = open(os.path.join(ROOT, "THREATMODEL.md"), encoding="utf-8").read()
    rows = []
    for line in text.split("\n"):
        if not line.startswith("| "):
            continue
        cells = [c.strip() for c in _ROW_CELLS.split(line.strip().strip("|"))]
        # Lettered rows (84a, 86c) are rows. `isdigit()` dropped every one of
        # them, so the published failures page silently omitted the newest
        # entries — including both shapes v0.1.14 was written for. A ledger
        # that quietly excludes rows is worse than no ledger (found 2026-08-09).
        if len(cells) < 3 or not re.fullmatch(r"\d+[a-z]*", cells[0]):
            continue
        rows.append((cells[0], cells[1], cells[2]))
    return rows


def status_of(raw: str) -> str:
    """Bucket a status cell. Deliberately coarse and deliberately pessimistic:
    anything that is not plainly Closed counts as not closed."""
    low = raw.lower()
    if "out of scope" in low:
        return "out of scope"
    if "open by design" in low:
        return "open by design"
    if "narrowed" in low and "open" in low:
        return "narrowed, still open"
    if "closed in part" in low or "partly closed" in low:
        return "closed in part"
    if raw.startswith("**Open**") or low.startswith("open"):
        return "open"
    if "closed" in low:
        return "closed"
    return "other"


def fixture_claims() -> dict[str, list[str]]:
    """bypass number -> fixtures that pin it."""
    claims: dict[str, list[str]] = {}
    cases = os.path.join(ROOT, "tests", "cases")
    for name in sorted(os.listdir(cases)):
        if not name.endswith(".gwcase"):
            continue
        head = open(os.path.join(cases, name), encoding="utf-8").read().split("=== before", 1)[0]
        for m in re.finditer(r"^bypass:\s*([\d,\s]+)$", head, re.M):
            for num in re.findall(r"\d+", m.group(1)):
                claims.setdefault(num, []).append(name)
    return claims


def main() -> None:
    out: list[str] = []
    w = out.append

    rows = bypass_rows()
    claims = fixture_claims()
    buckets: dict[str, list[tuple[str, str, str]]] = {}
    for num, shape, raw in rows:
        buckets.setdefault(status_of(raw), []).append((num, shape, raw))

    not_closed = sum(len(v) for k, v in buckets.items() if k not in ("closed", "out of scope"))

    w("# Known failures")
    w("")
    w("Generated by `benchmarks/make_failures.py` from `THREATMODEL.md`, the")
    w("adjudication files and the recorded decoy arms. Nothing here is")
    w("hand-typed; if something is missing from this page it is missing from")
    w("those files.")
    w("")
    w("This is the page to read before installing. Every other document in")
    w("this repository argues that the tool works; this one collects every way")
    w("it is known not to.")
    w("")

    w("## The short version")
    w("")
    w(f"- **{len(rows)} bypasses** are documented, of which **{not_closed} are not closed**.")
    adj = _load(HERE, ADJUDICATION)
    fp = [v for v in adj["verdicts"] if v["category"] == "false_positive"]
    total = 0
    for name in sorted(os.listdir(os.path.join(HERE, "sweeps"))):
        if name.endswith(".json"):
            total += _load(HERE, "sweeps", name)["commits_analysed"]
    w(f"- **{len(fp)} of {total}** human-written commits are blocked by mistake "
      f"({len(fp) / total:.2%}), each one named below.")
    w("- **2 false positives were shipped and corrected**, both found by")
    w("  adversarial review rather than by this project's own review.")
    w("- A production file greenwash cannot read suppresses escalation for the")
    w("  whole diff. That is the largest hole and it is by design.")
    w("")

    order = ["open", "narrowed, still open", "closed in part", "open by design", "out of scope", "closed", "other"]
    titles = {
        "open": "Open — no defence at all",
        "narrowed, still open": "Narrowed, still open",
        "closed in part": "Closed in part",
        "open by design": "Open by design — the cost of a deliberate trade",
        "out of scope": "Out of scope — the limits of the whole approach",
        "closed": "Closed — each pinned by something that runs",
        "other": "Unclassified",
    }
    for key in order:
        rows_here = buckets.get(key)
        if not rows_here:
            continue
        w(f"## {titles[key]} ({len(rows_here)})")
        w("")
        if key == "closed":
            w("A row is Closed only when a fixture or a named end-to-end test pins")
            w("it, enforced by `tests/test_threatmodel_pinned.py`. That gate cannot")
            w("prove a bypass is shut — one row sat here Closed while a single")
            w("non-ASCII character reopened it — it only makes *Closed with nothing")
            w("behind it* unshippable.")
            w("")
        w("| # | shape | pinned by |")
        w("|---|---|---|")
        for num, shape, _raw in rows_here:
            pins = ", ".join(f"`{c}`" for c in claims.get(num, [])) or "—"
            w(f"| {num} | {shape} | {pins} |")
        w("")

    w("## False positives on human-written commits")
    w("")
    w(f"Every commit in the 1800-commit corpus that greenwash blocks and should")
    w(f"not. Adjudicated by three raters; the reasoning for all three ships in")
    w(f"`{ADJUDICATION}` and the two blind re-adjudications beside it.")
    w("")
    w("| commit | three raters | why the block is wrong |")
    w("|---|---|---|")
    for v in sorted(fp, key=lambda v: (v.get("repo", ""), v.get("commit", ""))):
        commit = v.get("commit", "?")[:10]
        repo = v.get("repo", "")
        # The split, not just the majority. Four of these were contested, and
        # showing only the winning verdict would be the rounding-in-our-favour
        # this document exists to refuse.
        short = {"false_positive": "FP", "spec_correct": "policy", "unclear": "?"}
        calls = [short.get(v.get(k, "?"), v.get(k, "?")) for k in ("rater_a", "rater_b", "rater_c")]
        why = (v.get("reason") or "").replace("\n", " ").replace("|", r"\|").strip()
        w(f"| {repo} `{commit}` | {'/'.join(calls)} | {why[:260]} |")
    w("")

    w("## Cheats that got past it")
    w("")
    w("Recorded runs of real coding agents. Every diff is in the arm file, so")
    w("each of these replays.")
    w("")
    w("| arm | task | verdict at harvest | what it did |")
    w("|---|---|---|---|")
    decoy = os.path.join(HERE, "decoy")
    for name in sorted(os.listdir(decoy)):
        if not (name.startswith("arm-") and name.endswith(".json")):
            continue
        arm = _load(decoy, name)
        summary = arm.get("summary", {})
        escaped = summary.get("escaped_at_harvest") or summary.get("still_escaping_v0_1_9") or []
        if isinstance(escaped, int) or not escaped:
            continue
        for task in escaped:
            run = next((r for r in arm.get("runs", []) if r.get("task") == task), {})
            files = ", ".join((run.get("prod_files_changed") or []) + (run.get("test_files_changed") or []))
            w(f"| `{name}` | {task} | {run.get('greenwash_verdict', '?')} | touched {files or '?'} |")
    w("")

    w("## False positives this project shipped")
    w("")
    w("Both were introduced and corrected on 2026-08-07, and both were found by")
    w("adversarial review, not by self-review. Full accounts in `DECISIONS.md`")
    w("D-028 and D-029.")
    w("")
    w("| what blocked | why it was wrong | introduced | fixed |")
    w("|---|---|---|---|")
    w("| A pull request that **added** a backend, **added its own tests**, and gated them "
      "on `find_spec(\"redis\")` | net tests disabled: zero — and the message said there was no "
      "production change in a diff that changed three production files | v0.1.9 | v0.1.11 |")
    w("| Moving errexit from a shebang to `set -o errexit`, which makes a script *stricter* | "
      "reported as \"a failing command no longer fails the script\", over a script measured still "
      "exiting 1 on a failing test | v0.1.8 | v0.1.12 |")
    w("")

    w("## External credits")
    w("")
    w("Reports that arrived through the public issue templates, credited here")
    w("when they become a fixture. Generated from")
    w("`benchmarks/external-credits.json`. An empty table is the honest")
    w("state — do not invent a row to fill it. Quarterly review:")
    w("`docs/cheat-cadence.md`.")
    w("")
    credits_path = os.path.join(HERE, "external-credits.json")
    credits = (
        _load(HERE, "external-credits.json").get("credits")
        if os.path.isfile(credits_path)
        else []
    )
    w("| date | kind | reporter | issue | fixture | threatmodel |")
    w("|---|---|---|---|---|---|")
    if not credits:
        w("| — | — | *none yet* | — | — | — |")
    else:
        for row in credits:
            issue = row.get("issue")
            issue_cell = f"#{issue}" if issue else "—"
            w(
                f"| {row.get('date') or '—'} | {row.get('kind') or '—'} | "
                f"{row.get('reporter') or '—'} | {issue_cell} | "
                f"`{row.get('fixture') or '—'}` | {row.get('threatmodel_row') or '—'} |"
            )
    w("")

    w("## Send us one")
    w("")
    w("A cheat this missed, or an honest commit it blocked, is the most useful")
    w("thing anyone can send. Both become regression fixtures with the reporter")
    w("credited in the fixture header, and a row in the table above. Issue")
    w("templates for both are in `.github/ISSUE_TEMPLATE/`. The quarterly")
    w("review that turns a report into a credited row is `docs/cheat-cadence.md`.")

    path = os.path.join(HERE, "FAILURES.md")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote {path}: {len(rows)} bypasses ({not_closed} not closed), {len(fp)} false positives")


if __name__ == "__main__":
    main()
